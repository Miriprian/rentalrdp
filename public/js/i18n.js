const langState = { lang: "id" };
const LANG_KEYS = Object.keys(I18N.id); // id = sumber utama

function t(k, vars) {
  const d = I18N[langState.lang] && I18N[langState.lang][k] != null ? I18N[langState.lang] : I18N.id;
  let s = d[k];
  if (s == null) s = I18N.id[k] != null ? I18N.id[k] : k;
  if (vars) for (const [kk, vv] of Object.entries(vars)) s = s.replaceAll("{" + kk + "}", vv);
  return s;
}

function resolveLang(saved) {
  if (saved === "en" || saved === "id") return saved;
  try {
    const nav = (navigator.language || "id").toLowerCase();
    return nav.startsWith("id") ? "id" : "en";
  } catch { return "id"; }
}

function applyI18n() {
  document.querySelectorAll("[data-i18n]").forEach((el) => { const k = el.getAttribute("data-i18n"); if (k) el.textContent = t(k); });
  document.querySelectorAll("[data-i18n-html]").forEach((el) => { const k = el.getAttribute("data-i18n-html"); if (k) el.innerHTML = t(k); });
  document.querySelectorAll("[data-i18n-ph]").forEach((el) => { const k = el.getAttribute("data-i18n-ph"); if (k) el.placeholder = t(k); });
  document.querySelectorAll("[data-i18n-title]").forEach((el) => { const k = el.getAttribute("data-i18n-title"); if (k) el.title = t(k); });
  }

function langInit() {
  const saved = localStorage.getItem("lang") || null;
  langState.lang = resolveLang(saved);
  const sel = document.getElementById("langSel");
  if (sel) {
    sel.value = langState.lang;
    sel.addEventListener("change", () => {
      localStorage.setItem("lang", sel.value);
      langState.lang = sel.value;
      location.reload();
    });
  }
  applyI18n();
}